/** Looks up a seeded label when the catalog response has not arrived. */
export function findLookupFallback(
  lookup: string,
  id: number,
): LookupCatalogEntry | undefined {
  return LOOKUP_FALLBACKS[lookup]?.find((entry) => entry.id === id)
}
